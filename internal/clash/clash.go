// Package clash provides Clash/mihomo configuration generation for multiple proxy types.
package clash

import (
	"fmt"
	"strings"

	"merit/internal/model"
	"merit/internal/proxy"
	"merit/internal/proxy/shadowtls"
)

// Entry represents a Clash proxy entry.
type Entry struct {
	Name      string
	ProxyType string // mieru, naive, anytls, shadowtls
	Server    string
	Port      int
	Protocol  string
	Username  string
	Password  string

	// NaïveProxy specific
	Domain string
	TLS    bool

	// ShadowTLS specific
	HandshakeAddr  string
	TLSFingerprint string
	SNI            string
	// Backend is the shadowsocks data server behind ShadowTLS. mihomo needs its
	// credentials, because ShadowTLS itself carries no authentication.
	BackendPassword string
	BackendCipher   string
}

// DefaultShadowTLSBackendCipher is used when the backend cipher is not set.
const DefaultShadowTLSBackendCipher = "aes-256-gcm"

// BuildEntries flattens all enabled ports of a node into Clash entries.
// Nodes without a known address are skipped because they cannot be used yet.
//
// Ports mihomo cannot represent are skipped as well and reported by
// UnsupportedPorts: mihomo has no NaïveProxy outbound, and a ShadowTLS entry is
// unusable without the credentials of its backend data server.
func BuildEntries(n *model.Node) []Entry {
	host := n.Address
	if host == "" && n.SeenIP != "" {
		host = n.SeenIP
	}
	if host == "" {
		return nil
	}

	var out []Entry
	name := n.Name
	if name == "" {
		name = n.ID
	}

	for _, p := range n.Ports {
		if !p.Enabled {
			continue
		}
		label := p.Label
		if label == "" {
			label = fmt.Sprintf("%d", p.Port)
		}

		proxyType := model.NormalizeProxyType(p.ProxyType)

		entry := Entry{
			Name:      fmt.Sprintf("%s-%s", name, label),
			ProxyType: proxyType,
			Server:    host,
			Port:      p.Port,
			Protocol:  p.Protocol,
			Username:  p.Username,
			Password:  p.Password,
		}

		// Add proxy-specific fields
		switch proxyType {
		case model.ProxyTypeAnyTLS:
			entry.SNI = p.Domain
			entry.TLSFingerprint = p.EffectiveTLSFingerprint()
		case model.ProxyTypeNaive:
			// mihomo has no NaiveProxy outbound; skipping keeps the generated
			// subscription valid instead of shipping a proxy that cannot work.
			continue
		case model.ProxyTypeShadowTLS:
			entry.HandshakeAddr = shadowtls.Handshake(p)
			entry.SNI = p.Domain
			entry.BackendPassword = p.BackendPassword
			entry.BackendCipher = p.BackendCipher
			if entry.BackendPassword == "" {
				continue
			}
			if entry.BackendCipher == "" {
				entry.BackendCipher = DefaultShadowTLSBackendCipher
			}
		}

		out = append(out, entry)
	}
	return out
}

// UnsupportedPorts lists the enabled ports of a node that cannot be expressed in a
// mihomo configuration, together with the reason.
func UnsupportedPorts(n *model.Node) []string {
	var out []string
	name := n.Name
	if name == "" {
		name = n.ID
	}
	for _, p := range n.Ports {
		if !p.Enabled {
			continue
		}
		label := p.Label
		if label == "" {
			label = fmt.Sprintf("%d", p.Port)
		}
		switch model.NormalizeProxyType(p.ProxyType) {
		case model.ProxyTypeNaive:
			out = append(out, fmt.Sprintf("%s-%s (NaïveProxy)：mihomo 不支持该协议，请用 NaïveProxy 官方客户端导入分享链接", name, label))
		case model.ProxyTypeShadowTLS:
			if p.BackendPassword == "" {
				out = append(out, fmt.Sprintf("%s-%s (ShadowTLS)：未填写后端 shadowsocks 密码，无法生成客户端条目", name, label))
			}
		}
	}
	return out
}

// GenerateYAML renders a mihomo / Clash Meta configuration containing all entries.
func GenerateYAML(entries []Entry) string {
	return GenerateYAMLWithNotes(entries, nil)
}

// GenerateYAMLWithNotes renders the configuration and documents the ports that
// could not be represented as YAML comments.
func GenerateYAMLWithNotes(entries []Entry, notes []string) string {
	var b strings.Builder
	b.WriteString("# Generated by MieruPilot - Multi-Proxy Support\n")
	for _, note := range notes {
		b.WriteString("# 未包含: " + strings.ReplaceAll(note, "\n", " ") + "\n")
	}
	b.WriteString("mixed-port: 7890\n")
	b.WriteString("allow-lan: false\n")
	b.WriteString("mode: rule\n")
	b.WriteString("log-level: info\n\n")

	b.WriteString("proxies:\n")
	if len(entries) == 0 {
		b.WriteString("  []\n")
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		b.WriteString(renderProxyEntry(e))
		names = append(names, e.Name)
	}

	b.WriteString("\nproxy-groups:\n")
	b.WriteString("  - name: proxy\n")
	b.WriteString("    type: select\n")
	b.WriteString("    proxies:\n")
	if len(names) == 0 {
		b.WriteString("      - DIRECT\n")
	}
	for _, n := range names {
		b.WriteString(fmt.Sprintf("      - %s\n", yamlString(n)))
	}

	b.WriteString("\nrules:\n")
	b.WriteString("  - MATCH,proxy\n")
	return b.String()
}

func renderProxyEntry(e Entry) string {
	var b strings.Builder

	b.WriteString(fmt.Sprintf("  - name: %s\n", yamlString(e.Name)))

	switch e.ProxyType {
	case model.ProxyTypeMieru:
		transport := e.Protocol
		if transport == "" {
			transport = model.ProtocolTCP
		}
		b.WriteString("    type: mieru\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    transport: %s\n", transport))
		b.WriteString("    udp: true\n")
		b.WriteString(fmt.Sprintf("    username: %s\n", yamlString(e.Username)))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString(fmt.Sprintf("    handshake-mode: %s\n", model.DefaultHandshake))
		b.WriteString(fmt.Sprintf("    mtu: %d\n", model.DefaultMTU))
		b.WriteString(fmt.Sprintf("    multiplexing: %s\n", model.DefaultMultiplexing))
		b.WriteString(fmt.Sprintf("    traffic-pattern: %s\n", yamlString(model.DefaultTrafficPattern)))

	case model.ProxyTypeNaive:
		// mihomo has no NaiveProxy outbound. BuildEntries never emits such an
		// entry; the case stays so a hand-built Entry cannot produce a bogus
		// plain HTTP proxy that silently fails against a naive server.
		b.WriteString("    type: http\n")
		server := e.Domain
		if server == "" {
			server = e.Server
		}
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    username: %s\n", yamlString(e.Username)))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString("    tls: true\n")
		b.WriteString("    skip-cert-verify: false\n")

	case model.ProxyTypeAnyTLS:
		b.WriteString("    type: anytls\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		fingerprint := e.TLSFingerprint
		if fingerprint == "" {
			fingerprint = "chrome"
		}
		b.WriteString(fmt.Sprintf("    client-fingerprint: %s\n", yamlString(fingerprint)))
		b.WriteString("    udp: true\n")
		// The managed anytls-go server uses an ephemeral self-signed certificate.
		b.WriteString("    skip-cert-verify: true\n")
		if e.SNI != "" {
			b.WriteString(fmt.Sprintf("    sni: %s\n", yamlString(e.SNI)))
		}

	case model.ProxyTypeShadowTLS:
		// ShadowTLS is expressed as a shadowsocks proxy with the shadow-tls
		// plugin: "password" is the backend shadowsocks secret, while
		// plugin-opts.password is the ShadowTLS password.
		b.WriteString("    type: ss\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.BackendPassword)))
		b.WriteString(fmt.Sprintf("    cipher: %s\n", yamlString(e.BackendCipher)))
		// ShadowTLS is a TCP tunnel; a separate UDP backend is not deployed.
		b.WriteString("    udp: false\n")
		b.WriteString("    plugin: shadow-tls\n")
		b.WriteString("    plugin-opts:\n")
		sni := strings.TrimSpace(e.SNI)
		if sni == "" {
			sni = shadowtls.HandshakeHost(e.HandshakeAddr)
		}
		b.WriteString(fmt.Sprintf("      host: %s\n", yamlString(sni)))
		b.WriteString(fmt.Sprintf("      password: %s\n", yamlString(e.Password)))
		b.WriteString("      version: 3\n")
	}

	b.WriteString("\n")
	return b.String()
}

func yamlString(s string) string {
	if strings.ContainsAny(s, ":\"'\n") {
		escaped := strings.ReplaceAll(s, "\\", "\\\\")
		escaped = strings.ReplaceAll(escaped, "\"", "\\\"")
		escaped = strings.ReplaceAll(escaped, "\n", "\\n")
		return `"` + escaped + `"`
	}
	return s
}

// GenerateShareLink generates a share link for the given proxy port. Mieru links
// are produced by the mieru package, so an empty string is returned for them.
func GenerateShareLink(n *model.Node, p *model.Port) string {
	if model.NormalizeProxyType(p.ProxyType) == model.ProxyTypeMieru {
		return ""
	}
	return proxy.GenerateShareLink(n, p)
}

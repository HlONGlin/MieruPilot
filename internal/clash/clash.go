// Package clash provides Clash/mihomo configuration generation for multiple proxy types.
package clash

import (
	"fmt"
	"strings"

	"merit/internal/model"
	"merit/internal/proxy"
)

// Entry represents a Clash proxy entry.
type Entry struct {
	Name      string
	ProxyType string // mieru, naive, anytls, shadowtls
	Server    string
	Port      int
	Protocol  string
	Username  string
	Password  string

	// NaïveProxy specific
	Domain string
	TLS    bool

	// ShadowTLS specific
	HandshakeAddr string
	SNI           string
}

// BuildEntries flattens all enabled ports of a node into Clash entries.
// Nodes without a known address are skipped because they cannot be used yet.
func BuildEntries(n *model.Node) []Entry {
	host := n.Address
	if host == "" && n.SeenIP != "" {
		host = n.SeenIP
	}
	if host == "" {
		return nil
	}

	var out []Entry
	name := n.Name
	if name == "" {
		name = n.ID
	}

	for _, p := range n.Ports {
		if !p.Enabled {
			continue
		}
		label := p.Label
		if label == "" {
			label = fmt.Sprintf("%d", p.Port)
		}

		proxyType := p.ProxyType
		if proxyType == "" {
			proxyType = model.ProxyTypeMieru
		}

		entry := Entry{
			Name:      fmt.Sprintf("%s-%s", name, label),
			ProxyType: proxyType,
			Server:    host,
			Port:      p.Port,
			Protocol:  p.Protocol,
			Username:  p.Username,
			Password:  p.Password,
		}

		// Add proxy-specific fields
		switch proxyType {
		case model.ProxyTypeNaive:
			entry.Domain = p.Domain
			entry.TLS = true
		case model.ProxyTypeShadowTLS:
			entry.HandshakeAddr = p.HandshakeAddr
			if entry.HandshakeAddr == "" {
				entry.HandshakeAddr = "cloudflare.com:443"
			}
			entry.SNI = p.Domain
		}

		out = append(out, entry)
	}
	return out
}

// GenerateYAML renders a mihomo / Clash Meta configuration containing all entries.
func GenerateYAML(entries []Entry) string {
	var b strings.Builder
	b.WriteString("# Generated by MieruPilot - Multi-Proxy Support\n")
	b.WriteString("mixed-port: 7890\n")
	b.WriteString("allow-lan: false\n")
	b.WriteString("mode: rule\n")
	b.WriteString("log-level: info\n\n")

	b.WriteString("proxies:\n")
	if len(entries) == 0 {
		b.WriteString("  []\n")
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		b.WriteString(renderProxyEntry(e))
		names = append(names, e.Name)
	}

	b.WriteString("\nproxy-groups:\n")
	b.WriteString("  - name: proxy\n")
	b.WriteString("    type: select\n")
	b.WriteString("    proxies:\n")
	if len(names) == 0 {
		b.WriteString("      - DIRECT\n")
	}
	for _, n := range names {
		b.WriteString(fmt.Sprintf("      - %s\n", yamlString(n)))
	}

	b.WriteString("\nrules:\n")
	b.WriteString("  - MATCH,proxy\n")
	return b.String()
}

func renderProxyEntry(e Entry) string {
	var b strings.Builder

	b.WriteString(fmt.Sprintf("  - name: %s\n", yamlString(e.Name)))

	switch e.ProxyType {
	case model.ProxyTypeMieru:
		transport := e.Protocol
		if transport == "" {
			transport = model.ProtocolTCP
		}
		b.WriteString("    type: mieru\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    transport: %s\n", transport))
		b.WriteString("    udp: true\n")
		b.WriteString(fmt.Sprintf("    username: %s\n", yamlString(e.Username)))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString(fmt.Sprintf("    handshake-mode: %s\n", model.DefaultHandshake))
		b.WriteString(fmt.Sprintf("    mtu: %d\n", model.DefaultMTU))
		b.WriteString(fmt.Sprintf("    multiplexing: %s\n", model.DefaultMultiplexing))
		b.WriteString(fmt.Sprintf("    traffic-pattern: %s\n", yamlString(model.DefaultTrafficPattern)))

	case model.ProxyTypeNaive:
		server := e.Domain
		if server == "" {
			server = e.Server
		}
		b.WriteString("    type: http\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    username: %s\n", yamlString(e.Username)))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString("    tls: true\n")
		b.WriteString("    skip-cert-verify: false\n")

	case model.ProxyTypeAnyTLS:
		b.WriteString("    type: trojan\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString("    udp: true\n")
		b.WriteString("    skip-cert-verify: false\n")

	case model.ProxyTypeShadowTLS:
		b.WriteString("    type: ss\n")
		b.WriteString(fmt.Sprintf("    server: %s\n", yamlString(e.Server)))
		b.WriteString(fmt.Sprintf("    port: %d\n", e.Port))
		b.WriteString(fmt.Sprintf("    password: %s\n", yamlString(e.Password)))
		b.WriteString("    cipher: aes-256-gcm\n")
		b.WriteString("    plugin: shadow-tls\n")
		b.WriteString("    plugin-opts:\n")
		b.WriteString(fmt.Sprintf("      host: %s\n", yamlString(e.HandshakeAddr)))
		b.WriteString("      version: 3\n")
		if e.SNI != "" {
			b.WriteString(fmt.Sprintf("      sni: %s\n", yamlString(e.SNI)))
		}
	}

	b.WriteString("\n")
	return b.String()
}

func yamlString(s string) string {
	if strings.ContainsAny(s, ":\"'\n") {
		escaped := strings.ReplaceAll(s, "\\", "\\\\")
		escaped = strings.ReplaceAll(escaped, "\"", "\\\"")
		escaped = strings.ReplaceAll(escaped, "\n", "\\n")
		return `"` + escaped + `"`
	}
	return s
}

// GenerateShareLink generates a share link for the given proxy port
func GenerateShareLink(n *model.Node, p *model.Port) string {
	host := n.Address
	if host == "" && n.SeenIP != "" {
		host = n.SeenIP
	}
	if host == "" {
		return ""
	}

	proxyType := p.ProxyType
	if proxyType == "" {
		proxyType = model.ProxyTypeMieru
	}

	pm := proxy.NewManager()
	switch proxyType {
	case model.ProxyTypeMieru:
		// Keep using the existing mieru link generation
		return "" // Will be handled by existing mieru package
	case model.ProxyTypeNaive:
		return pm.GenerateShareLink(proxyType, proxy.ShareLinkParams{
			Host:     host,
			Port:     p.Port,
			Username: p.Username,
			Password: p.Password,
			Domain:   p.Domain,
		})
	case model.ProxyTypeAnyTLS:
		return pm.GenerateShareLink(proxyType, proxy.ShareLinkParams{
			Host:     host,
			Port:     p.Port,
			Password: p.Password,
		})
	case model.ProxyTypeShadowTLS:
		return pm.GenerateShareLink(proxyType, proxy.ShareLinkParams{
			Host:          host,
			Port:          p.Port,
			Password:      p.Password,
			HandshakeAddr: p.HandshakeAddr,
		})
	}
	return ""
}
